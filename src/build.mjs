/**
 * Build every derived artifact from src/skin.mjs:
 *   lib/client.js          browser half (dsh module-loader protocol, CJS factory)
 *   fixtures/skin-tokens.json  the override layer, for verification
 *   preview/index.html     standalone light+dark preview of the skin
 *
 * Hand-rolled on purpose: the client half is a dozen lines of ESM-free JS, so a
 * bundler would only add a toolchain the user has to install.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ID, NAME, TOKENS, STYLES } from './skin.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const write = (rel, body) => {
  const full = path.join(root, rel);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, body);
  return rel;
};

// ── browser half ────────────────────────────────────────────────────────────
const client = `/* ${NAME} skin for DeepSeek Harness — generated by \`node src/build.mjs\`.
 * Do not edit: change src/skin.mjs and rebuild.
 *
 * Loaded through the DSH client module protocol: executing this script only
 * registers the factory; the plugin body runs when the loader materializes it. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(ID)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;

    var ID = ${JSON.stringify(ID)};
    /** token name → { light, dark }; folded into the active theme snapshot. */
    var TOKENS = ${JSON.stringify(TOKENS, null, 0)};
    var STYLES = ${JSON.stringify(STYLES)};

    /** Mount the signature stylesheet for exactly the owning plugin lifetime. */
    function installStyles(ctx) {
      if (typeof document === "undefined") return;
      ctx.effect(() => {
        var tag = document.createElement("style");
        tag.dataset.plugin = ID;
        tag.dataset.pluginCss = ID + "/thought-lite.css";
        tag.textContent = STYLES;
        document.head.appendChild(tag);
        return () => {
          tag.remove();
        };
      }, ID + ": stylesheet");
    }

    /**
     * Stack one token override layer over whichever built-in theme is active.
     * A skin, not a theme: the user's light/dark/system choice still decides
     * the colour scheme, this only repaints it.
     */
    function apply(ctx) {
      try {
        var theme = ctx.theme;
        if (!theme || typeof theme.overrideTokens !== "function") {
          console.warn("[" + ID + "] theme service unavailable; skin not applied");
          return;
        }
        installStyles(ctx);
        ctx.effect(() => theme.overrideTokens(ID, TOKENS), ID + ": token layer");
      } catch (error) {
        // A skin must never take the GUI down with it.
        console.warn("[" + ID + "] failed to apply", error);
      }
    }

    exports.ID = ID;
    exports.TOKENS = TOKENS;
    exports.STYLES = STYLES;
    exports.inject = ["theme"];
    exports.apply = apply;
    return module.exports;
  },
});
`;

